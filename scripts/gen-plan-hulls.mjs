// node scripts/gen-plan-hulls.mjs  -> proxy/src/plahulls.mjs
// Builds a small static pennant-number -> ship-name table for PLAN classes that Japan's Joint Staff reports name (class + 艦番号).
// Sources: Wikidata (CC0; operator = PLA Navy, pennant number P879, class P289) + Wikipedia class tables (CC BY-SA 4.0) for classes Wikidata lacks (Type 054A).
// Names are facts about public hull numbers; the output only keeps `type code -> hull -> English name`. Re-run occasionally; it is NOT used at runtime for anything but labels.
import { writeFileSync } from "node:fs";
const UA = { "User-Agent": "gods-eye-view-research/1.0 (+https://numenaslan-cell.github.io/gods-eye-mobile/)" };
const out = {};
const put = (code, hull, name) => { hull = String(hull).trim(); name = String(name).trim(); if (!code || !/^\d{2,3}$/.test(hull) || !name) return; (out[code] = out[code] || {})[hull] = name; };
const q = `SELECT ?sLabel ?pn ?clsLabel WHERE { ?op rdfs:label "People's Liberation Army Navy"@en . ?s wdt:P137 ?op . ?s wdt:P879 ?pn . OPTIONAL{?s wdt:P289 ?cls} SERVICE wikibase:label { bd:serviceParam wikibase:language "en". } } LIMIT 3000`;
const wd = await (await fetch("https://query.wikidata.org/sparql?format=json&query=" + encodeURIComponent(q), { headers: UA })).json();
for (const b of wd.results.bindings) {
  const cls = (b.clsLabel && b.clsLabel.value) || "", name = b.sLabel.value.replace(/^Chinese (destroyer|frigate|ship|aircraft carrier|corvette|cruiser|submarine)\s+/i, "");
  let code = (/Type (\d{3}[A-Z]?)/.exec(cls) || [])[1];
  if (!code && /Fuyu/i.test(cls)) code = "901"; if (!code && /Qiandaohu|Fuchi/i.test(cls)) code = "903"; if (!code && /Kuznetsov|aircraft carrier/i.test(cls)) code = "CV";
  if (!code && /Fujian/.test(name)) code = "CV";
  put(code, b.pn.value, name);
}
// Wikipedia class tables (Type 054A frigates; also fills gaps for 052C/052D/055)
for (const [page, code] of [["Type_054A_frigate", "054A"], ["Type_052D_destroyer", "052D"], ["Type_052C_destroyer", "052C"], ["Type_055_destroyer", "055"]]) {
  const j = await (await fetch(`https://en.wikipedia.org/w/api.php?action=parse&page=${page}&prop=wikitext&format=json&formatversion=2&redirects=1`, { headers: UA })).json();
  const w = (j.parse && j.parse.wikitext) || "";
  for (const row of w.split(/\n\|-/)) {
    const cells = row.split(/\n[|!](?![|}\-])/).map((c) => c.trim()).filter(Boolean);
    const h = /^(\d{3})\b/.exec((cells[0] || "").replace(/^[|!]\s*/, "")); if (!h) continue;
    const nm = /\/\s*(?:''|\[\[)?([A-Z][A-Za-z' -]+?)(?:''|\]\]|\|)/.exec(cells[1] || "") || /Chinese (?:frigate|destroyer) ([A-Z][A-Za-z -]+?)(?: \(|\||\])/.exec(cells[1] || "");
    if (nm && !(out[code] && out[code][h[1]])) put(code, h[1], nm[1]);
  }
}
const body = "/* generated by scripts/gen-plan-hulls.mjs (Wikidata CC0 + Wikipedia class tables CC BY-SA 4.0) — labels only. Key: PLAN type code -> pennant (hull) number -> name. */\nexport const PLAN_HULLS = " + JSON.stringify(out, null, 0).replace(/\},"/g, '},\n"') + ";\n";
writeFileSync(new URL("../proxy/src/plahulls.mjs", import.meta.url), body);
console.log(Object.entries(out).map(([k, v]) => k + ":" + Object.keys(v).length).join(" "));
