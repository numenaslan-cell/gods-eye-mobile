// Zero-dependency build: node build.mjs
//  1. assets/textures.js  <- inlines assets/textures/*.jpg as data URIs (so it also works from file://)
//  2. assets/app.bundle.js <- src/vendor.js (React + three.js bundle) + src/app.js
import { readFileSync, writeFileSync } from "node:fs";
const here = new URL(".", import.meta.url);
const read = (p) => readFileSync(new URL(p, here), "utf8");
const b64 = (p) => "data:image/jpeg;base64," + readFileSync(new URL(p, here)).toString("base64");
writeFileSync(
  new URL("assets/textures.js", here),
  `/* generated by build.mjs — NASA Blue Marble / Black Marble (public domain) */\nwindow.GODS_EYE_TEXTURES=${JSON.stringify({ day: b64("assets/textures/earth-day.jpg"), night: b64("assets/textures/earth-night.jpg") })};\n`
);
writeFileSync(new URL("assets/app.bundle.js", here), "(function(){\n" + read("src/vendor.js") + ";\n" + read("src/app.js") + "\n})();\n"); // IIFE: no globals leak
console.log("built assets/textures.js + assets/app.bundle.js");
